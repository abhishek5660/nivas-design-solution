// ---------------- History ----------------
interface Rev { id: string; version: number; label: string; createdAt: string; author: string }

function diffDocs(a: SceneDoc, b: SceneDoc) {
  const added = b.order.filter((i) => !a.nodes[i]).map((i) => b.nodes[i].name);
  const removed = a.order.filter((i) => !b.nodes[i]).map((i) => a.nodes[i].name);
  const changed: string[] = [];
  for (const i of b.order) {
    if (!a.nodes[i]) continue;
    const x = a.nodes[i];
    const y = b.nodes[i];
    const bits: string[] = [];
    if (JSON.stringify(x.size) !== JSON.stringify(y.size)) bits.push(`size ${Math.round(x.size.w)}×${Math.round(x.size.h)}×${Math.round(x.size.d)} → ${Math.round(y.size.w)}×${Math.round(y.size.h)}×${Math.round(y.size.d)}`);
    if (JSON.stringify(x.position) !== JSON.stringify(y.position) || x.rotationY !== y.rotationY) bits.push('moved');
    if (JSON.stringify(x.materials) !== JSON.stringify(y.materials) || JSON.stringify(x.subMaterials) !== JSON.stringify(y.subMaterials)) bits.push('materials');
    if (JSON.stringify(x.params) !== JSON.stringify(y.params)) bits.push('configuration');
    if (bits.length) changed.push(`${y.name}: ${bits.join(', ')}`);
  }
  return { added, removed, changed };
}

export function HistoryTab() {
  const projectId = useEditor((s) => s.projectId)!;
  const doc = useEditor((s) => s.doc);
  const access = useEditor((s) => s.access);
  const meta = useEditor((s) => s.meta);
  const [revs, setRevs] = useState<Rev[] | null>(null);
  const [label, setLabel] = useState('');
  const [cmp, setCmp] = useState<{ rev: Rev; diff: ReturnType<typeof diffDocs> } | null>(null);
  const [restore, setRestore] = useState<Rev | null>(null);
  const [importAsk, setImportAsk] = useState<{ text: string; name: string } | null>(null);
  const [busy, setBusy] = useState(false);
  const [tplAsk, setTplAsk] = useState<string | null>(null);
  const file = useRef<HTMLInputElement>(null);

  const load = () => api<{ revisions: Rev[] }>(`/api/projects/${projectId}/revisions`).then((r) => setRevs(r.revisions)).catch((e) => useEditor.getState().toast('error', e.message));
  useEffect(() => { load(); }, [projectId]); // eslint-disable-line react-hooks/exhaustive-deps

  async function compare(r: Rev) {
    try {
      const { revision } = await api<{ revision: { data: SceneDoc } }>(`/api/projects/${projectId}/revisions/${r.id}`);
      setCmp({ rev: r, diff: diffDocs(revision.data, doc) });
    } catch (e) {
      useEditor.getState().toast('error', (e as Error).message);
    }
  }
  async function doRestore() {
    if (!restore) return;
    setBusy(true);
    try {
      // make sure nothing unsaved is lost: persist the current state as a version first
      await saveNow({ manual: true, label: 'Before restore' });
      await api(`/api/projects/${projectId}/revisions/${restore.id}`, { method: 'POST' });
      window.location.reload();
    } catch (e) {
      useEditor.getState().toast('error', (e as Error).message);
      setBusy(false);
    }
  }
  async function saveTemplate(name: string) {
    try {
      const nodes = Object.values(doc.nodes);
      await api('/api/catalog', { method: 'POST', body: JSON.stringify({ kind: 'TEMPLATE', name: name.trim(), category: doc.category, data: { doc, category: doc.category, summary: `${nodes.length} components · room ${Math.round(Math.max(...doc.room.points.map((p) => p[0])))} × ${Math.round(Math.max(...doc.room.points.map((p) => p[1])))} mm` } }) });
      useEditor.getState().toast('success', 'Saved as a template. Find it under Templates.');
    } catch (e) {
      useEditor.getState().toast('error', (e as Error).message);
    }
  }
  async function onFile(f: File) {
    const text = await f.text();
    const r = parseProjectImport(text);
    if (!r.ok) return useEditor.getState().toast('error', `Import rejected - your design was not changed. ${r.errors.slice(0, 2).join(' ')}`);
    setImportAsk({ text, name: r.value.project.name });
  }
  function doImport() {
    if (!importAsk) return;
    const r = parseProjectImport(importAsk.text);
    if (r.ok) {
      useEditor.getState().replaceDoc(r.value.data);
      useEditor.getState().toast('success', 'Design replaced from file (undo with Ctrl+Z).');
    }
    setImportAsk(null);
  }

  return (
    <div className="mx-auto max-w-4xl space-y-4 p-5">
      <Panel>
        <h3 className="mb-2 font-display text-xl font-semibold">Save a named version</h3>
        <div className="flex gap-2">
          <input className="input" placeholder="e.g. Approved by customer" value={label} maxLength={120} onChange={(e) => setLabel(e.target.value)} />
          <button className="btn btn-gold" disabled={access === 'VIEW'} onClick={async () => { const ok = await saveNow({ manual: true, label: label.trim() || 'Manual save' }); if (ok) { setLabel(''); load(); } }}>Save version</button>
        </div>
        <div className="mt-3 flex flex-wrap gap-2">
          <button className="btn btn-sm" disabled={access === 'VIEW'} onClick={() => setTplAsk(meta?.name ?? 'My template')}>Save design as template</button>
          <button className="btn btn-sm" onClick={() => exportFromServer('project.json')}>Export project (JSON)</button>
          <input ref={file} type="file" accept=".json,application/json" className="hidden" onChange={(e) => { const f = e.target.files?.[0]; if (f) onFile(f); e.target.value = ''; }} />
          <button className="btn btn-sm" disabled={access === 'VIEW'} onClick={() => file.current?.click()}>Replace design from JSON…</button>
        </div>
      </Panel>
      <Panel>
        <h3 className="mb-2 font-display text-xl font-semibold">Version history</h3>
        {!revs ? <Spinner /> : revs.length === 0 ? <p className="text-sm text-mute">No saved versions yet.</p> : (
          <ul className="divide-y divide-sand">
            {revs.map((r, i) => (
              <li key={r.id} className="flex flex-wrap items-center gap-3 py-2 text-sm">
                <span className="chip">v{r.version}</span>
                <div className="min-w-0 flex-1"><div className="truncate font-medium">{r.label || 'Saved version'}</div><div className="text-xs text-mute">{r.author} · {timeAgo(r.createdAt)}{i === 0 ? ' · latest' : ''}</div></div>
                <button className="btn btn-sm" onClick={() => compare(r)}>Compare with current</button>
                <button className="btn btn-sm" disabled={access === 'VIEW'} onClick={() => setRestore(r)}>Restore</button>
              </li>
            ))}
          </ul>
        )}
      </Panel>
      {cmp && (
        <Panel>
          <div className="mb-2 flex items-center justify-between"><h3 className="font-display text-xl font-semibold">Current vs v{cmp.rev.version}</h3><button className="text-xs underline" onClick={() => setCmp(null)}>close</button></div>
          {!cmp.diff.added.length && !cmp.diff.removed.length && !cmp.diff.changed.length && <p className="text-sm text-mute">No differences.</p>}
          {cmp.diff.added.length > 0 && <p className="text-sm"><b className="text-ok">Added since:</b> {cmp.diff.added.join(', ')}</p>}
          {cmp.diff.removed.length > 0 && <p className="text-sm"><b className="text-danger">Removed since:</b> {cmp.diff.removed.join(', ')}</p>}
          {cmp.diff.changed.length > 0 && <ul className="mt-1 list-disc pl-5 text-sm">{cmp.diff.changed.map((c) => <li key={c}>{c}</li>)}</ul>}
        </Panel>
      )}
      {restore && <Confirm title={`Restore v${restore.version}?`} confirmLabel="Restore" busy={busy} message={<>Your current design is saved as a version first, then <b>{meta?.name}</b> is set back to v{restore.version}. History is never deleted.</>} onCancel={() => setRestore(null)} onConfirm={doRestore} />}
      {tplAsk !== null && (
        <Dialog title="Save design as template" onClose={() => setTplAsk(null)} footer={<><button className="btn" onClick={() => setTplAsk(null)}>Cancel</button><button className="btn btn-primary" disabled={!tplAsk.trim()} onClick={() => { saveTemplate(tplAsk.trim()); setTplAsk(null); }}>Save template</button></>}>
          <label className="block"><span className="label">Template name</span><input className="input" value={tplAsk} maxLength={120} onChange={(e) => setTplAsk(e.target.value)} /></label>
          <p className="mt-2 text-xs text-mute">The whole design (room, components, materials, pricing settings) is copied. Projects started from it are independent.</p>
        </Dialog>
      )}
      {importAsk && <Confirm title="Replace the current design?" confirmLabel="Replace" message={<>The file “{importAsk.name}” is valid. It will replace the design in this project. You can undo this.</>} onCancel={() => setImportAsk(null)} onConfirm={doImport} />}
    </div>
  );
}

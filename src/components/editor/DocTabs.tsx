  const assembly = useMemo(() => assemblyInfo(doc), [doc]);
  const checks = useMemo(() => {
    // validate the production outputs against the saved design (single source of truth)
    const boq = buildBoq(doc);
    const cutArea = cl.pieces.reduce((a, p) => a + (p.length * p.width) / 1e6, 0);
    const boqArea = boq.items.filter((i) => i.unit === 'm²' && i.section !== 'Glass & mirror').reduce((a, i) => a + i.netQty, 0);
    const nested = nests.reduce((a, n) => a + n.sheets.reduce((b, s) => b + s.placements.length, 0), 0);
    const hwQty = boq.items.filter((i) => i.section === 'Hardware' || i.section === 'Lighting').length;
    return [
      { ok: Math.abs(cutArea - boqArea) < 0.05, text: `Cut-list area ${cutArea.toFixed(2)} m² matches BOQ net sheet area ${boqArea.toFixed(2)} m²` },
      { ok: nested === cl.pieces.length - nests.reduce((a, n) => a + n.oversized.length, 0), text: `${nested} of ${cl.pieces.length} pieces placed on boards` },
      { ok: new Set(cl.pieces.map((p) => p.label)).size === cl.pieces.length, text: 'Every panel has a unique label' },
      { ok: hwQty > 0, text: `${hwQty} hardware lines derived from the model` },
    ];
  }, [doc, cl, nests]);
  const setDocPart = useEditor((s) => s.setDocPart);
  if (!cl.pieces.length) return <div className="p-8"><EmptyState title="No panels to produce" hint="Add a wardrobe, cabinet or TV panel to generate a cut list." /></div>;
  const sheets = nests.reduce((a, n) => a + n.sheets.length, 0);

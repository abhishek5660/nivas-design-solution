            <thead><tr className="text-left text-xs uppercase tracking-wider text-mute"><th className="py-1">Label</th><th>Name</th><th>Type</th><th className="text-right">W</th><th className="text-right">H</th><th className="text-right">D</th><th className="text-right">Elev.</th></tr></thead>

function download(name: string, data: BlobPart, mime: string) {
  const url = URL.createObjectURL(new Blob([data], { type: mime }));
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

/** Saves first, then downloads the document generated by the server from the saved data. */
export async function exportFromServer(type: string) {
  const s = useEditor.getState();
  if (!s.projectId) return;
  if (s.saveStatus !== 'saved') {
    const ok = await saveNow({ manual: false });
    if (!ok) {
      s.toast('error', 'The latest changes could not be saved, so the export was not generated. Fix the save problem first.');
      return;
    }
  }
  const a = document.createElement('a');
  a.href = `/api/projects/${s.projectId}/export?type=${encodeURIComponent(type)}`;
  a.click();
}

